using System;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using Assets._Project.Develop.Runtime.Gameplay.EntitiesCore;
using UnityEditor;

namespace Assets._Project.Develop.Editor
{
    public static class EntityAPIGenerator
    {
        private const string OutputPath = "Assets/_Project/Develop/Runtime/Gameplay/EntitiesCore/Generated/EntityAPI.cs";
        private const string ComponentSuffix = "Component";

        [InitializeOnLoadMethod]
        [MenuItem("Tools/Gameplay/Generate Entity API")]
        public static void Generate()
        {
            Type entityType = typeof(Entity);
            Type componentType = typeof(IEntityComponent);
            Type[] types = componentType.Assembly.GetTypes()
                .Where(type => type.IsInterface == false && type.IsAbstract == false && componentType.IsAssignableFrom(type))
                .OrderBy(type => type.FullName, StringComparer.Ordinal)
                .ToArray();

            var code = new StringBuilder();
            code.AppendLine("// Generated by EntityAPIGenerator. Do not edit manually.");
            code.AppendLine($"namespace {entityType.Namespace}");
            code.AppendLine("{");
            code.AppendLine($"    public partial class {entityType.Name}");
            code.AppendLine("    {");

            foreach (Type type in types)
                AppendComponent(code, type);

            code.AppendLine("    }");
            code.AppendLine("}");
            string content = code.ToString().Replace("\r\n", "\n");

            if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == content)
                return;

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, content);
            AssetDatabase.Refresh();
        }

        private static void AppendComponent(StringBuilder code, Type type)
        {
            string name = type.Name.EndsWith(ComponentSuffix, StringComparison.Ordinal)
                ? type.Name.Substring(0, type.Name.Length - ComponentSuffix.Length)
                : type.Name;
            string typeName = GetTypeName(type);
            FieldInfo[] fields = type.GetFields(BindingFlags.Public | BindingFlags.Instance)
                .OrderBy(field => field.Name, StringComparer.Ordinal)
                .ToArray();

            code.AppendLine($"        public {typeName} {name}C => GetComponent<{typeName}>();");

            bool hasValue = fields.Length == 1 && fields[0].Name == "Value";

            if (hasValue)
                code.AppendLine($"        public {GetTypeName(fields[0].FieldType)} {name} => {name}C.Value;");

            string parameters = string.Join(", ", fields.Select(field => $"{GetTypeName(field.FieldType)} {GetParameterName(field)}"));
            string assignments = string.Join(", ", fields.Select(field => $"{field.Name} = {GetParameterName(field)}"));
            code.AppendLine();
            code.AppendLine($"        public Entity Add{name}({parameters})");
            code.AppendLine($"            => AddComponent(new {typeName} {{ {assignments} }});");

            if (hasValue)
            {
                Type valueType = fields[0].FieldType;

                if (valueType.IsAbstract == false && valueType.GetConstructor(Type.EmptyTypes) != null
                    && typeof(UnityEngine.Object).IsAssignableFrom(valueType) == false)
                {
                    code.AppendLine();
                    code.AppendLine($"        public Entity Add{name}() => Add{name}(new {GetTypeName(valueType)}());");
                }

                code.AppendLine();
                code.AppendLine($"        public bool TryGet{name}(out {GetTypeName(valueType)} @value)");
                code.AppendLine("        {");
                code.AppendLine($"            bool result = TryGetComponent(out {typeName} component);");
                code.AppendLine("            @value = result ? component.Value : default;");
                code.AppendLine();
                code.AppendLine("            return result;");
                code.AppendLine("        }");
            }

            code.AppendLine();
        }

        private static string GetParameterName(FieldInfo field)
            => "@" + char.ToLowerInvariant(field.Name[0]) + field.Name.Substring(1);

        private static string GetTypeName(Type type)
        {
            if (type.IsGenericType == false)
                return "global::" + type.FullName;

            string name = type.GetGenericTypeDefinition().FullName;
            name = name.Substring(0, name.IndexOf('`'));
            string arguments = string.Join(", ", type.GetGenericArguments().Select(GetTypeName));

            return $"global::{name}<{arguments}>";
        }
    }
}
