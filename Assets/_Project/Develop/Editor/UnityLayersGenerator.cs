using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Assets._Project.Develop.Editor
{
    public static class UnityLayersGenerator
    {
        private const int LayerCount = 32;
        private const string OutputPath = "Assets/_Project/Develop/Runtime/Utilities/Layers/UnityLayers.cs";
        private const string OutputNamespace = "Assets._Project.Develop.Runtime.Utilities.Layers";

        [InitializeOnLoadMethod]
        [MenuItem("Tools/Gameplay/Generate Unity Layers")]
        public static void Generate()
        {
            var layers = new StringBuilder();
            var masks = new StringBuilder();
            var usedNames = new HashSet<string>();

            for (int layer = 0; layer < LayerCount; layer++)
            {
                string layerName = LayerMask.LayerToName(layer);

                if (string.IsNullOrEmpty(layerName))
                    continue;

                string name = GetUniqueName(layerName, layer, usedNames);
                string literal = GetStringLiteral(layerName);
                layers.AppendLine($"        public static readonly int Layer{name} = global::UnityEngine.LayerMask.NameToLayer({literal});");
                masks.AppendLine($"        public static readonly int LayerMask{name} = 1 << Layer{name};");
            }

            var code = new StringBuilder();
            code.AppendLine("// Generated by UnityLayersGenerator. Do not edit manually.");
            code.AppendLine($"namespace {OutputNamespace}");
            code.AppendLine("{");
            code.AppendLine("    public static class UnityLayers");
            code.AppendLine("    {");
            code.Append(layers);
            code.AppendLine();
            code.Append(masks);
            code.AppendLine("    }");
            code.AppendLine("}");
            string content = code.ToString().Replace("\r\n", "\n");

            if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == content)
                return;

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, content);
            AssetDatabase.Refresh();
        }

        private static string GetUniqueName(string layerName, int layer, HashSet<string> usedNames)
        {
            var identifier = new StringBuilder();

            foreach (char character in layerName)
            {
                if (char.IsLetterOrDigit(character) || character == '_')
                    identifier.Append(character);
            }

            string name = identifier.Length > 0 ? identifier.ToString() : "Unnamed";

            if (usedNames.Contains("Layer" + name) || usedNames.Contains("LayerMask" + name))
                name += "_" + layer;

            while (usedNames.Contains("Layer" + name) || usedNames.Contains("LayerMask" + name))
                name += "_";

            usedNames.Add("Layer" + name);
            usedNames.Add("LayerMask" + name);

            return name;
        }

        private static string GetStringLiteral(string value)
        {
            var literal = new StringBuilder("\"");

            foreach (char character in value)
            {
                if (character == '\\' || character == '"')
                    literal.Append('\\').Append(character);
                else if (char.IsControl(character) || character == '\u2028' || character == '\u2029')
                    literal.Append("\\u").Append(((int)character).ToString("x4"));
                else
                    literal.Append(character);
            }

            return literal.Append('"').ToString();
        }
    }
}
